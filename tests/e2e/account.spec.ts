import { test, expect } from '@playwright/test';

test('customer account has a responsive sign-up, personal dashboard, saved details, orders and updates', async ({ page, isMobile }) => {
  test.setTimeout(120000);
  const email = `account-${crypto.randomUUID()}@example.test`;
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/account');
  await expect(page.locator('.account-entry')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'A place that feels like you.' })).toBeVisible();
  await expect.poll(() => page.locator('.account-entry-editorial img').evaluate((element) => (element as HTMLImageElement).complete && (element as HTMLImageElement).naturalWidth > 0), { timeout: 45000 }).toBe(true);
  await page.screenshot({ path: `test-results/customer-entry-${isMobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('group', { name: 'Your Maison', exact: true }).getByRole('button', { name: 'Create an account' }).click();
  await page.getByLabel('Full name', { exact: true }).fill('Amara Demo');
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('AccountDemo2026!');
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text');
  await page.locator('form').getByRole('button', { name: 'Create an account', exact: true }).click();
  await expect(page.locator('.account-hero')).toContainText('Good to see you, Amara.', { timeout: 45000 });
  await expect(page.getByRole('heading', { name: 'Your first signature awaits.' })).toBeVisible();
  await page.locator('.account-sidebar nav').getByRole('button', { name: 'My details', exact: true }).click();
  await page.getByLabel('Full name', { exact: true }).fill('Amara Maison');
  await page.getByRole('button', { name: 'Save my details', exact: true }).click();
  await expect(page.locator('.account-details-form').getByRole('status')).toContainText('Your changes are saved.');
  await page.reload();
  await expect(page.locator('.account-identity')).toContainText('Amara Maison');
  const snapshot = await (await page.request.get('/api/shop')).json();
  const product = snapshot.products.find((product: { stock: Record<string, number> }) => Object.values(product.stock).some((stock) => stock > 0));
  const size = Object.keys(product.stock).find((size) => product.stock[size] > 0);
  const orderReply = await page.request.post('/api/shop', { headers: { origin: 'http://127.0.0.1:3100' }, data: { action: 'order', cart: [{ productId: product.id, size, quantity: 1 }], currency: 'EUR', payment: 'card', idempotencyKey: crypto.randomUUID(), recipient: { name: 'Amara Maison', email, address: '12 Demo Road', city: 'Cotonou', country: 'BJ' } } });
  expect(orderReply.ok()).toBe(true);
  const { order } = await orderReply.json();
  await page.goto('/app/orders');
  await expect(page.locator('.customer-order')).toContainText(order.id);
  await page.locator('.account-sidebar nav').getByRole('button', { name: 'My orders', exact: true }).click();
  await page.getByRole('button', { name: 'View order', exact: true }).click();
  await expect(page.locator('.customer-order-info')).toContainText('12 Demo Road');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download demo invoice', exact: true }).click();
  expect((await download).suggestedFilename()).toContain(order.id.toLowerCase());
  await page.locator('.site-header').getByRole('button', { name: 'Français', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Mes commandes', exact: true })).toBeVisible();
  await expect(page.locator('.customer-order')).toContainText(order.id);
  await page.locator('.site-header').getByRole('button', { name: 'English', exact: true }).click();
  await page.locator('.account-sidebar nav').getByRole('button', { name: /^My updates/ }).click();
  await expect(page.getByRole('heading', { name: 'Your order is confirmed', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Mark all as read', exact: true }).click();
  await expect(page.locator('.account-updates .is-unread')).toHaveCount(0);
  await page.locator('.account-sidebar nav').getByRole('button', { name: 'Your Maison', exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `test-results/customer-dashboard-${isMobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect((await page.request.get('/api/shop?admin=1')).status()).toBe(403);
  await page.locator('.account-sidebar-end').getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.locator('.account-entry')).toBeVisible();
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('AccountDemo2026!');
  await page.locator('form').getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('.account-identity')).toContainText('Amara Maison', { timeout: 45000 });
  await expect(page.locator('.customer-order')).toContainText(order.id);
  expect(errors).toEqual([]);
});

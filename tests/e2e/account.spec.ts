import { test, expect } from '@playwright/test';
import { changeLanguage, seedPrivacy } from './navigation';

test.beforeEach(async ({ page }) => { await seedPrivacy(page); });

test('customer account supports registration, private details, address book, orders and updates', async ({ page, isMobile }) => {
  test.setTimeout(120000);
  const email = `account-${crypto.randomUUID()}@example.test`;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/account');
  await page.waitForURL(/\/login\?next=%2Fapp$/, { waitUntil: 'domcontentloaded', timeout: 45000 });
  await expect(page.locator('.reference-account-entry')).toHaveCount(1);
  await expect(page.locator('.reference-account-entry')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Login to your account', exact: true })).toBeVisible();
  const headingBox = await page.getByRole('heading', { name: 'Login to your account', exact: true }).boundingBox();
  const headerBox = await page.locator('.site-header').boundingBox();
  expect(headingBox!.y).toBeGreaterThanOrEqual(headerBox!.y + headerBox!.height);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const auth = page.locator('.reference-account-form .reference-auth');
  await auth.locator('.reference-auth-tabs').getByRole('button', { name: 'Create an account', exact: true }).click();
  await auth.getByRole('combobox', { name: 'Title *', exact: true }).selectOption('mr');
  await auth.getByLabel('First name *', { exact: true }).fill('Amara');
  await auth.getByLabel('Last name *', { exact: true }).fill('Demo');
  await auth.getByLabel('Email *', { exact: true }).fill(email);
  await auth.getByLabel('Password *', { exact: true }).fill('AccountDemo2026!');
  await auth.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(auth.getByLabel('Password *', { exact: true })).toHaveAttribute('type', 'text');
  await page.screenshot({ path: `test-results/customer-entry-${isMobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  await auth.locator('form').getByRole('button', { name: 'Create an account', exact: true }).click();
  await expect(page.locator('.exact-personal-heading')).toContainText('Welcome Amara', { timeout: 45000 });
  await expect(page.getByRole('heading', { name: 'Personal area', exact: true })).toBeVisible();
  await expect(page.locator('.exact-personal-summary-card')).toHaveCount(4);
  await expect(page.locator('.exact-personal-email')).toHaveText(email);
  await expect(page.locator('#footer .exact-footer-main')).toBeVisible();
  const navigation = page.locator('.exact-personal-sidebar nav');
  await navigation.getByRole('link', { name: 'Personal information', exact: true }).click();
  const details = page.locator('.reference-profile');
  await expect(details.getByRole('textbox', { name: /^Email \*/ })).toHaveAttribute('readonly', '');
  await details.getByLabel('Last name *', { exact: true }).fill('Maison');
  await details.getByLabel('Mobile phone number', { exact: true }).fill('+229 01 00 00 00 00');
  await details.getByRole('combobox', { name: 'Day', exact: true }).selectOption('15');
  await details.getByRole('combobox', { name: 'Month', exact: true }).selectOption('6');
  await details.getByRole('combobox', { name: 'Year', exact: true }).selectOption('1994');
  await details.getByRole('combobox', { name: 'Country *', exact: true }).selectOption('BJ');
  await details.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(details.getByRole('status')).toContainText('Your changes are saved.');
  await page.reload();
  await expect(details.getByLabel('Last name *', { exact: true })).toHaveValue('Maison');
  await expect(details.getByLabel('Mobile phone number', { exact: true })).toHaveValue('+229 01 00 00 00 00');
  await expect(details.getByRole('combobox', { name: 'Day', exact: true })).toHaveValue('15');
  await expect(details.getByRole('combobox', { name: 'Country *', exact: true })).toHaveValue('BJ');
  await page.screenshot({ path: `test-results/customer-profile-${isMobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  await navigation.getByRole('link', { name: 'Addresses', exact: true }).click();
  await expect(page).toHaveURL(/\/app\/addresses$/);
  await page.getByRole('button', { name: 'Add an address', exact: true }).click();
  const address = page.locator('.account-address-editor');
  await address.getByLabel('Address label (optional)', { exact: true }).fill('Home');
  await address.getByLabel('Street address', { exact: true }).fill('12 Saved Demo Road');
  await address.getByLabel('City', { exact: true }).fill('Cotonou');
  await address.getByRole('combobox', { name: 'Country', exact: true }).selectOption('BJ');
  await address.getByRole('button', { name: 'Save address', exact: true }).click();
  await expect(page.locator('.account-saved-address')).toContainText('12 Saved Demo Road');
  await page.reload();
  await expect(page.locator('.account-saved-address')).toContainText('Default address');
  const snapshot = await (await page.request.get('/api/shop')).json();
  const product = snapshot.products.find((product: { stock: Record<string, number> }) => Object.values(product.stock).some(stock => stock > 0));
  const size = Object.keys(product.stock).find(size => product.stock[size] > 0);
  await page.goto('/product/' + product.id);
  await expect(page.locator('.site-header')).toHaveAttribute('data-ready', 'true');
  const savedWishlist = page.waitForResponse(response => response.url().endsWith('/api/shop') && response.request().method() === 'POST' && response.request().postDataJSON()?.action === 'wishlist');
  await page.locator('.pdp-buy-buttons').first().getByRole('button', { name: 'Add to wishlist', exact: true }).click();
  expect((await savedWishlist).ok()).toBe(true);
  await page.goto('/app/wishlist');
  await expect(page.getByRole('heading', { name: 'Wishlist', exact: true, level: 1 })).toBeVisible();
  await expect(page.locator('.reference-wishlist-list')).toContainText(product.name.en);
  await expect(navigation.getByRole('link', { name: 'Wishlist', exact: true })).toHaveAttribute('aria-current', 'page');
  const reply = await page.request.post('/api/shop', { headers: { origin: 'http://127.0.0.1:3100' }, data: { action: 'order', cart: [{ productId: product.id, size, quantity: 1 }], currency: 'EUR', payment: 'card', idempotencyKey: crypto.randomUUID(), recipient: { name: 'Amara Maison', email, address: '12 Demo Road', city: 'Cotonou', country: 'BJ' } } });
  expect(reply.ok()).toBe(true);
  const { order } = await reply.json();
  await page.goto('/app/orders');
  await expect(page.locator('.customer-order')).toContainText(order.id);
  await page.getByRole('button', { name: 'View order', exact: true }).click();
  await expect(page.locator('.customer-order-info')).toContainText('12 Demo Road');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download demo invoice', exact: true }).click();
  expect((await download).suggestedFilename()).toContain(order.id.toLowerCase());
  await changeLanguage(page, 'Français');
  await expect(page.getByRole('heading', { name: 'Commandes et retours', exact: true })).toBeVisible();
  await expect(page.locator('.customer-order')).toContainText(order.id);
  await changeLanguage(page, 'English');
  await page.locator('.exact-personal-services').getByRole('link', { name: /^My updates/ }).click();
  await expect(page.getByRole('heading', { name: 'Your order is confirmed', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Mark all as read', exact: true }).click();
  await expect(page.locator('.account-updates .is-unread')).toHaveCount(0);
  await page.locator('.site-header .wordmark').click();
  await expect(page).toHaveURL('/');
  await page.locator('.site-header .profile-button').click();
  await expect(page).toHaveURL(/\/app$/);
  await page.screenshot({ path: `test-results/customer-dashboard-${isMobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await page.request.get('/api/shop?admin=1')).status()).toBe(403);
  await page.locator('.exact-personal-sidebar').getByRole('button', { name: 'Logout', exact: true }).click();
  await expect(page.locator('.reference-account-entry')).toBeVisible();
  const login = page.locator('.reference-account-form form');
  await login.getByLabel('Email *', { exact: true }).fill(email);
  await login.getByLabel('Password *', { exact: true }).fill('AccountDemo2026!');
  await login.getByRole('button', { name: 'Login', exact: true }).click();
  await expect(page.locator('.exact-personal-heading')).toContainText('Welcome Amara', { timeout: 45000 });
  await expect(page.locator('.exact-personal-email')).toHaveText(email);
  await navigation.getByRole('link', { name: 'Orders and returns', exact: true }).click();
  await expect(page.locator('.customer-order')).toContainText(order.id);
  expect(errors).toEqual([]);
});

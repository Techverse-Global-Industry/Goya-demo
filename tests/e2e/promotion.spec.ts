import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { formatMoney } from '../../lib/commerce';
import type { CartQuote, Currency, Order, Product, StoreSnapshot } from '../../lib/types';
import { selectProductSize } from './catalog-navigation';
import { seedPrivacy } from './navigation';

test('GOYA10 express guest checkout saves paid prices, invoice and one stock allocation', async ({ page }) => {
  test.setTimeout(120000);
  await seedPrivacy(page);
  const externalRequests: string[] = [];
  // Exercise only Goya's simulator; an accidental external provider call is blocked and fails the test.
  await page.route('**/*', async route => {
    const url = new URL(route.request().url());
    if ((url.protocol === 'http:' || url.protocol === 'https:') && !['127.0.0.1', 'localhost'].includes(url.hostname)) {
      externalRequests.push(url.href);
      await route.abort();
    } else await route.continue();
  });
  await page.goto('/product/francesco');
  await expect(page.getByRole('heading', { level: 1, name: 'Le Francesco Loafer', exact: true })).toBeVisible();
  const before = await (await page.request.get('/api/shop')).json() as StoreSnapshot;
  const product = before.products.find(item => item.id === 'francesco')!;
  const size = Object.keys(product.stock).find(variant => product.stock[variant] > 0)!;
  expect(size).toBeTruthy();
  const originalStock = product.stock[size];
  await selectProductSize(page, product.id, size);
  await page.locator('.pdp-purchase').getByRole('button', { name: 'Add to bag', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await page.goto('/bag');
  const promo = page.locator('.exact-bag-promo');
  await promo.getByRole('button', { name: 'Promo code', exact: true }).click();
  await promo.getByLabel('Enter your promo code', { exact: true }).fill('goya10');
  const quoted = page.waitForResponse(response => {
    if (!response.url().endsWith('/api/shop') || response.request().method() !== 'POST') return false;
    return response.request().postDataJSON()?.action === 'cartQuote';
  });
  await promo.getByRole('button', { name: 'Apply', exact: true }).click();
  const quoteResponse = await quoted;
  expect(quoteResponse.ok()).toBe(true);
  const { quote } = await quoteResponse.json() as { quote: CartQuote };
  const currency = quoteResponse.request().postDataJSON().currency as Currency;
  const money = (amount: number) => formatMoney(amount, currency, 'en');
  expect(quote.promoCode).toBe('GOYA10');
  expect(quote.discount).toBeGreaterThan(0);
  await expect(promo.getByRole('status')).toContainText('Promo code applied.');
  await expect(page.locator('.exact-bag-grand-total strong')).toHaveText(money(quote.total));
  await page.locator('.exact-bag-express').getByRole('link', { name: 'Continue with PayPal (demo)', exact: true }).click();
  await expect(page).toHaveURL(/\/checkout\?payment=paypal$/);
  await expect(page.locator('.checkout-express-notice')).toContainText('PayPal');
  await page.getByRole('button', { name: 'Continue as a guest', exact: true }).click();
  const checkout = page.locator('.checkout-reference');
  await checkout.locator('#shipping-name').fill('Promotion Demo');
  await checkout.locator('#shipping-email').fill(`promotion-${crypto.randomUUID()}@example.test`);
  await checkout.locator('#shipping-address').fill('12 Demonstration Avenue');
  await checkout.locator('#shipping-city').fill('Cotonou');
  await checkout.locator('#shipping-country').selectOption('BJ');
  await checkout.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(checkout.getByRole('radio', { name: /PayPal/ })).toBeChecked();
  await expect(checkout.locator('.checkout-address-review')).toContainText('12 Demonstration Avenue');
  await expect(checkout.locator('.checkout-promotion')).toContainText('GOYA10');
  await expect(checkout.locator('.checkout-promotion')).toContainText('−' + money(quote.discount));
  await expect(checkout.locator('.order-summary .grand-total strong')).toHaveText(money(quote.total));
  await checkout.getByRole('button', { name: 'Confirm demo order', exact: true }).click();
  await expect(checkout.locator('.demo-payment')).toContainText('Demo PayPal wallet');
  await expect(checkout.locator('.payment-amount')).toHaveText(money(quote.total));
  const unapproved = await (await page.request.get('/api/shop')).json() as StoreSnapshot;
  expect(unapproved.orders).toEqual([]);
  expect(unapproved.products.find(item => item.id === product.id)!.stock[size]).toBe(originalStock);
  const committed = page.waitForResponse(response => {
    if (!response.url().endsWith('/api/shop') || response.request().method() !== 'POST') return false;
    return response.request().postDataJSON()?.action === 'order';
  });
  await checkout.getByRole('button', { name: 'Approve demo payment', exact: true }).click();
  const orderResponse = await committed;
  expect(orderResponse.ok()).toBe(true);
  const { order } = await orderResponse.json() as { order: Order };
  expect(order).toMatchObject({ customerId: null, payment: 'paypal', currency, promoCode: quote.promoCode, originalSubtotal: quote.originalSubtotal, discount: quote.discount, subtotal: quote.subtotal, shipping: quote.shipping, total: quote.total });
  expect(order.lines).toHaveLength(quote.lines.length);
  for (const [index, line] of quote.lines.entries()) expect(order.lines[index]).toMatchObject({...line});
  await expect(checkout.getByRole('heading', { name: 'A beautiful choice.', exact: true })).toBeVisible();
  await expect(checkout.locator('.confirmation-references')).toContainText(order.id);
  await expect(checkout.locator('.checkout-promotion')).toContainText('−' + money(quote.discount));
  await expect(checkout.locator('.order-summary .grand-total strong')).toHaveText(money(quote.total));
  const snapshot = await (await page.request.get('/api/shop')).json() as StoreSnapshot;
  expect(snapshot.orders).toHaveLength(1);
  expect(snapshot.orders[0]).toMatchObject({...order});
  expect(snapshot.products.find(item => item.id === product.id)!.stock[size]).toBe(originalStock - 1);
  await expect.poll(() => page.evaluate(() => {
    const preferences = JSON.parse(localStorage.getItem('maison-goya:v1')!);
    return { cart: preferences.cart, promoCode: preferences.promoCode };
  })).toEqual({ cart: [], promoCode: '' });
  const downloading = page.waitForEvent('download');
  await checkout.getByRole('button', { name: 'Download demo invoice', exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toContain(order.id.toLowerCase());
  const invoice = await readFile((await download.path())!, 'utf8');
  for (const expected of [order.id, 'GOYA10', money(quote.originalSubtotal), money(quote.discount), money(quote.subtotal), money(quote.total)]) expect(invoice).toContain(expected);
  await page.reload();
  await expect(checkout.locator('.confirmation-references')).toContainText(order.id);
  const repeated = await page.request.post('/api/shop', { headers: { origin: new URL(page.url()).origin }, data: orderResponse.request().postDataJSON() });
  expect(repeated.ok()).toBe(true);
  expect((await repeated.json()).order.id).toBe(order.id);
  const after = await (await page.request.get('/api/shop')).json() as StoreSnapshot;
  expect(after.orders.map(item => item.id)).toEqual([order.id]);
  expect(after.products.find((item: Product) => item.id === product.id)!.stock[size]).toBe(originalStock - 1);
  expect(externalRequests).toEqual([]);
});
